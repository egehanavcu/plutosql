-- h02_inventory: stok yönetimi şeması
CREATE TABLE H02_ITEMS (
  ITEM_ID       NUMBER(9) NOT NULL,
  UNIT_COST     NUMBER(12,4),
  SUPPLIER_ID   NUMBER(9),
  DESCR         VARCHAR2(150),
  CONSTRAINT H02_ITEMS_PK PRIMARY KEY (ITEM_ID)
)
/
CREATE TABLE H02_WAREHOUSES (
  WAREHOUSE_ID  NUMBER(5) NOT NULL,
  REGION        VARCHAR2(6),
  HANDLING_PCT  NUMBER(5,2),
  CONSTRAINT H02_WAREHOUSES_PK PRIMARY KEY (WAREHOUSE_ID)
)
/
CREATE TABLE H02_MOVEMENTS (
  MOVEMENT_ID   NUMBER(12) NOT NULL,
  WAREHOUSE_ID  NUMBER(5) NOT NULL,
  ITEM_ID       NUMBER(9) NOT NULL,
  QTY           NUMBER(9),
  MOVED_AT      DATE,
  CONSTRAINT H02_MOVEMENTS_PK PRIMARY KEY (MOVEMENT_ID)
)
/
CREATE TABLE H02_MOVEMENT_COSTED (
  MOVEMENT_ID   NUMBER(12) NOT NULL,
  WAREHOUSE_ID  NUMBER(5) NOT NULL,
  ITEM_ID       NUMBER(9) NOT NULL,
  QTY           NUMBER(9),
  COST_AMOUNT   NUMBER(18,4),
  CONSTRAINT H02_MOVEMENT_COSTED_PK PRIMARY KEY (MOVEMENT_ID)
)
/
CREATE TABLE H02_STOCK_LEVELS (
  WAREHOUSE_ID  NUMBER(5) NOT NULL,
  ITEM_ID       NUMBER(9) NOT NULL,
  ON_HAND       NUMBER(12),
  STOCK_VALUE   NUMBER(20,4),
  MIN_QTY       NUMBER(9),
  CONSTRAINT H02_STOCK_LEVELS_PK PRIMARY KEY (WAREHOUSE_ID, ITEM_ID)
)
/
CREATE TABLE H02_REORDER_PROPOSALS (
  WAREHOUSE_ID  NUMBER(5) NOT NULL,
  ITEM_ID       NUMBER(9) NOT NULL,
  SUPPLIER_ID   NUMBER(9),
  ORDER_QTY     NUMBER(12),
  EST_COST      NUMBER(20,4),
  CONSTRAINT H02_REORDER_PROPOSALS_PK PRIMARY KEY (WAREHOUSE_ID, ITEM_ID)
)
/
CREATE TABLE H02_STOCK_LEVELS_SEED AS SELECT * FROM H02_STOCK_LEVELS WHERE 1 = 0
/
