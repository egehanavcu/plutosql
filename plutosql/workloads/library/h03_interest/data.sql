-- h03_interest: deterministik veri (ORA_HASH). 25 mevduat ürünü, 300 şube, 30 000 hesap
-- (~%80 aktif, ~%5 sıfır/negatif bakiyeli).
INSERT /*+ APPEND */ INTO H03_PRODUCTS (PRODUCT_CODE, ANNUAL_RATE, DESCR)
SELECT 'VDL' || LPAD(LEVEL, 3, '0'), ROUND(5 + MOD(ORA_HASH(LEVEL, 4294967295, 301), 4500) / 100, 4),
       'vadeli mevduat urunu ' || LEVEL
  FROM dual CONNECT BY LEVEL <= 25
/
COMMIT
/
INSERT /*+ APPEND */ INTO H03_BRANCHES (BRANCH_ID, WITHHOLDING_PCT, CITY)
SELECT LEVEL, CASE MOD(ORA_HASH(LEVEL, 4294967295, 311), 3) WHEN 0 THEN 5 WHEN 1 THEN 10 ELSE 15 END,
       'sehir ' || MOD(LEVEL, 81)
  FROM dual CONNECT BY LEVEL <= 300
/
COMMIT
/
INSERT /*+ APPEND */ INTO H03_ACCOUNTS_SEED (ACCOUNT_ID, BRANCH_ID, PRODUCT_CODE, BALANCE, ACCRUED, STATUS)
SELECT LEVEL,
       1 + MOD(ORA_HASH(LEVEL, 4294967295, 321), 300),
       'VDL' || LPAD(1 + MOD(ORA_HASH(LEVEL, 4294967295, 322), 25), 3, '0'),
       CASE WHEN MOD(ORA_HASH(LEVEL, 4294967295, 323), 20) = 0 THEN 0
            ELSE ROUND(MOD(ORA_HASH(LEVEL, 4294967295, 324), 100000000) / 100, 2) END,
       ROUND(MOD(ORA_HASH(LEVEL, 4294967295, 325), 1000000) / 100, 2),
       CASE WHEN MOD(ORA_HASH(LEVEL, 4294967295, 326), 5) = 0 THEN 'BLOCKED' ELSE 'ACTIVE' END
  FROM dual CONNECT BY LEVEL <= 30000
 ORDER BY 1
/
COMMIT
