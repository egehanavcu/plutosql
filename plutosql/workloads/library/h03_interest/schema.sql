-- h03_interest: günlük faiz tahakkuku şeması
CREATE TABLE H03_PRODUCTS (
  PRODUCT_CODE    VARCHAR2(10) NOT NULL,
  ANNUAL_RATE     NUMBER(7,4),
  DESCR           VARCHAR2(60),
  CONSTRAINT H03_PRODUCTS_PK PRIMARY KEY (PRODUCT_CODE)
)
/
CREATE TABLE H03_BRANCHES (
  BRANCH_ID       NUMBER(5) NOT NULL,
  WITHHOLDING_PCT NUMBER(5,2),
  CITY            VARCHAR2(30),
  CONSTRAINT H03_BRANCHES_PK PRIMARY KEY (BRANCH_ID)
)
/
CREATE TABLE H03_ACCOUNTS (
  ACCOUNT_ID      NUMBER(10) NOT NULL,
  BRANCH_ID       NUMBER(5) NOT NULL,
  PRODUCT_CODE    VARCHAR2(10) NOT NULL,
  BALANCE         NUMBER(16,2),
  ACCRUED         NUMBER(16,2) NOT NULL,
  STATUS          VARCHAR2(8),
  CONSTRAINT H03_ACCOUNTS_PK PRIMARY KEY (ACCOUNT_ID)
)
/
CREATE TABLE H03_ACCRUALS (
  ACCOUNT_ID      NUMBER(10) NOT NULL,
  GROSS           NUMBER(14,2),
  TAX             NUMBER(14,2),
  NET             NUMBER(14,2),
  CONSTRAINT H03_ACCRUALS_PK PRIMARY KEY (ACCOUNT_ID)
)
/
CREATE TABLE H03_ACCOUNTS_SEED AS SELECT * FROM H03_ACCOUNTS WHERE 1 = 0
/
