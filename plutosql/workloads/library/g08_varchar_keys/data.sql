-- Üretilmiş iş yükü verisi (deterministik): g08_varchar_keys
INSERT /*+ APPEND */ INTO G08_VARCHAR_KEYS_R1 (K, V, PAD)
SELECT 'K' || TO_CHAR(LEVEL), ROUND(0.5 + MOD(ORA_HASH(LEVEL, 4294967295, 10), 1000000) / 1000000, 6), RPAD('x', 50, 'x')
  FROM dual CONNECT BY LEVEL <= 50000
/
COMMIT
/
