INSERT /*+ APPEND */ INTO G08_VARCHAR_KEYS_SRC (ID, GRP, K1, K2, AMOUNT)
SELECT LEVEL,
       1 + MOD(ORA_HASH(LEVEL, 4294967295, 1), 200),
       'K' || TO_CHAR(1 + MOD(ORA_HASH(LEVEL, 4294967295, 20), 10000)),
       'K' || TO_CHAR(1 + MOD(ORA_HASH(LEVEL, 4294967295, 21), 30)),
       ROUND(MOD(ORA_HASH(LEVEL, 4294967295, 2), 1000000) / 100, 2)
  FROM dual CONNECT BY LEVEL <= 20000
 ORDER BY 1
/
COMMIT
/
