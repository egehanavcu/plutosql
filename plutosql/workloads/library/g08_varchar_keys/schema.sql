-- Üretilmiş iş yükü şeması: g08_varchar_keys
CREATE TABLE G08_VARCHAR_KEYS_SRC (
  ID       NUMBER(12) NOT NULL,
  GRP      NUMBER(9) NOT NULL,
  K1       VARCHAR2(12),
  K2       VARCHAR2(12),
  AMOUNT   NUMBER(18,2),
  CONSTRAINT G08_VARCHAR_KEYS_SRC_PK PRIMARY KEY (ID)
)
/
CREATE TABLE G08_VARCHAR_KEYS_R1 (
  K        VARCHAR2(12) NOT NULL,
  V        NUMBER(12,6),
  PAD      VARCHAR2(50),
  CONSTRAINT G08_VARCHAR_KEYS_R1_PK PRIMARY KEY (K)
)
/
CREATE TABLE G08_VARCHAR_KEYS_R2 (
  K        VARCHAR2(12) NOT NULL,
  V        NUMBER(12,6),
  CONSTRAINT G08_VARCHAR_KEYS_R2_PK PRIMARY KEY (K)
)
/
CREATE TABLE G08_VARCHAR_KEYS_T1 (
  ID       NUMBER(12) NOT NULL,
  GRP      NUMBER(9) NOT NULL,
  K1       VARCHAR2(12),
  K2       VARCHAR2(12),
  AMOUNT   NUMBER(18,2),
  CONSTRAINT G08_VARCHAR_KEYS_T1_PK PRIMARY KEY (ID)
)
/
CREATE TABLE G08_VARCHAR_KEYS_T2 (
  GRP      NUMBER(9) NOT NULL,
  TOTAL    NUMBER(20,2),
  CNT      NUMBER(12),
  CONSTRAINT G08_VARCHAR_KEYS_T2_PK PRIMARY KEY (GRP)
)
/
CREATE TABLE G08_VARCHAR_KEYS_T2_SEED AS SELECT * FROM G08_VARCHAR_KEYS_T2 WHERE 1 = 0
/
