INSERT /*+ APPEND */ INTO G09_SCALE_60K_R1 (K, V, PAD)
SELECT LEVEL, ROUND(0.5 + MOD(ORA_HASH(LEVEL, 4294967295, 1010), 1000000) / 1000000, 6), RPAD('x', 60, 'x')
  FROM dual CONNECT BY LEVEL <= 100000
/
