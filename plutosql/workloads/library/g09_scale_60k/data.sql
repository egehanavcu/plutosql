INSERT /*+ APPEND */ INTO G09_SCALE_60K_SRC (ID, GRP, K1, AMOUNT)
SELECT LEVEL,
       1 + MOD(ORA_HASH(LEVEL, 4294967295, 1001), 200),
       1 + MOD(ORA_HASH(LEVEL, 4294967295, 1020), 50000),
       ROUND(MOD(ORA_HASH(LEVEL, 4294967295, 1002), 1000000) / 100, 2)
  FROM dual CONNECT BY LEVEL <= 60000
 ORDER BY 1
/
COMMIT
