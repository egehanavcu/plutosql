-- h01_invoicing: fatura kesimi şeması
CREATE TABLE H01_PRODUCTS (
  PRODUCT_ID    NUMBER(9) NOT NULL,
  CATEGORY      VARCHAR2(8) NOT NULL,
  LIST_PRICE    NUMBER(12,2),
  DESCR         VARCHAR2(120),
  CONSTRAINT H01_PRODUCTS_PK PRIMARY KEY (PRODUCT_ID)
)
/
CREATE TABLE H01_CUSTOMERS (
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  DISCOUNT_PCT  NUMBER(5,2),
  SEGMENT       VARCHAR2(10),
  ADDRESS       VARCHAR2(200),
  CONSTRAINT H01_CUSTOMERS_PK PRIMARY KEY (CUSTOMER_ID)
)
/
CREATE TABLE H01_TAX_RATES (
  CATEGORY      VARCHAR2(8) NOT NULL,
  VAT_PCT       NUMBER(5,2),
  CONSTRAINT H01_TAX_RATES_PK PRIMARY KEY (CATEGORY)
)
/
CREATE TABLE H01_ORDER_LINES (
  ORDER_ID      NUMBER(12) NOT NULL,
  LINE_NO       NUMBER(4) NOT NULL,
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  PRODUCT_ID    NUMBER(9) NOT NULL,
  CATEGORY      VARCHAR2(8) NOT NULL,
  QTY           NUMBER(9),
  STATUS        VARCHAR2(10),
  CONSTRAINT H01_ORDER_LINES_PK PRIMARY KEY (ORDER_ID, LINE_NO)
)
/
CREATE TABLE H01_INVOICE_LINES (
  ORDER_ID      NUMBER(12) NOT NULL,
  LINE_NO       NUMBER(4) NOT NULL,
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  NET_AMOUNT    NUMBER(14,2),
  VAT_AMOUNT    NUMBER(14,2),
  CONSTRAINT H01_INVOICE_LINES_PK PRIMARY KEY (ORDER_ID, LINE_NO)
)
/
CREATE TABLE H01_CUSTOMER_BALANCE (
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  OPEN_AMOUNT   NUMBER(16,2),
  INVOICE_COUNT NUMBER(9),
  CONSTRAINT H01_CUSTOMER_BALANCE_PK PRIMARY KEY (CUSTOMER_ID)
)
/
CREATE TABLE H01_CUSTOMER_BALANCE_SEED AS SELECT * FROM H01_CUSTOMER_BALANCE WHERE 1 = 0
/
