-- h04_loyalty: sadakat puanı şeması
CREATE TABLE H04_MERCHANTS (
  MERCHANT_ID   NUMBER(9) NOT NULL,
  MCC           VARCHAR2(4) NOT NULL,
  BONUS_PCT     NUMBER(5,2),
  NAME          VARCHAR2(80),
  CONSTRAINT H04_MERCHANTS_PK PRIMARY KEY (MERCHANT_ID)
)
/
CREATE TABLE H04_CAMPAIGNS (
  MCC           VARCHAR2(4) NOT NULL,
  MULTIPLIER    NUMBER(4,2),
  CONSTRAINT H04_CAMPAIGNS_PK PRIMARY KEY (MCC)
)
/
CREATE TABLE H04_POS_TXN (
  TXN_ID        NUMBER(12) NOT NULL,
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  MERCHANT_ID   NUMBER(9) NOT NULL,
  MCC           VARCHAR2(4) NOT NULL,
  AMOUNT        NUMBER(12,2),
  STATUS        VARCHAR2(10),
  CONSTRAINT H04_POS_TXN_PK PRIMARY KEY (TXN_ID)
)
/
CREATE TABLE H04_POINT_EVENTS (
  TXN_ID        NUMBER(12) NOT NULL,
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  POINTS        NUMBER(10),
  CONSTRAINT H04_POINT_EVENTS_PK PRIMARY KEY (TXN_ID)
)
/
CREATE TABLE H04_LOYALTY_BALANCE (
  CUSTOMER_ID   NUMBER(9) NOT NULL,
  POINTS        NUMBER(12),
  EVENTS        NUMBER(9),
  CONSTRAINT H04_LOYALTY_BALANCE_PK PRIMARY KEY (CUSTOMER_ID)
)
/
CREATE TABLE H04_LOYALTY_BALANCE_SEED AS SELECT * FROM H04_LOYALTY_BALANCE WHERE 1 = 0
/
