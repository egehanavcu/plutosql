-- h04_loyalty: deterministik veri (ORA_HASH). 60 MCC kampanyası, 10 000 işyeri, 40 000 POS işlemi
-- (~%70 onaylı), 8 000 müşteri. İşlemin MCC'si işyerininkiyle aynı ifadeden türetilir.
INSERT /*+ APPEND */ INTO H04_CAMPAIGNS (MCC, MULTIPLIER)
SELECT 'M' || LPAD(LEVEL, 3, '0'), ROUND(1 + MOD(ORA_HASH(LEVEL, 4294967295, 401), 300) / 100, 2)
  FROM dual CONNECT BY LEVEL <= 60
/
COMMIT
/
INSERT /*+ APPEND */ INTO H04_MERCHANTS (MERCHANT_ID, MCC, BONUS_PCT, NAME)
SELECT LEVEL,
       'M' || LPAD(1 + MOD(ORA_HASH(LEVEL, 4294967295, 411), 60), 3, '0'),
       MOD(ORA_HASH(LEVEL, 4294967295, 412), 51),
       RPAD('isyeri ' || LEVEL, 80, '.')
  FROM dual CONNECT BY LEVEL <= 10000
/
COMMIT
/
INSERT /*+ APPEND */ INTO H04_POS_TXN (TXN_ID, CUSTOMER_ID, MERCHANT_ID, MCC, AMOUNT, STATUS)
SELECT txn_id, customer_id, merchant_id,
       'M' || LPAD(1 + MOD(ORA_HASH(merchant_id, 4294967295, 411), 60), 3, '0'),
       amount, status
  FROM (SELECT LEVEL AS txn_id,
               1 + MOD(ORA_HASH(LEVEL, 4294967295, 421), 8000) AS customer_id,
               1 + MOD(ORA_HASH(LEVEL, 4294967295, 422), 10000) AS merchant_id,
               ROUND(1 + MOD(ORA_HASH(LEVEL, 4294967295, 423), 500000) / 100, 2) AS amount,
               CASE WHEN MOD(ORA_HASH(LEVEL, 4294967295, 424), 10) < 7 THEN 'APPROVED'
                    WHEN MOD(ORA_HASH(LEVEL, 4294967295, 424), 10) < 9 THEN 'DECLINED' ELSE 'REVERSED' END AS status
          FROM dual CONNECT BY LEVEL <= 40000)
 ORDER BY txn_id
/
COMMIT
/
INSERT /*+ APPEND */ INTO H04_LOYALTY_BALANCE_SEED (CUSTOMER_ID, POINTS, EVENTS)
SELECT LEVEL, MOD(ORA_HASH(LEVEL, 4294967295, 431), 100000), MOD(ORA_HASH(LEVEL, 4294967295, 432), 300)
  FROM dual
 WHERE MOD(ORA_HASH(LEVEL, 4294967295, 433), 3) <> 0
CONNECT BY LEVEL <= 8000
/
COMMIT
