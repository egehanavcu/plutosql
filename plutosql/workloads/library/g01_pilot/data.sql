INSERT /*+ APPEND */ INTO G01_PILOT_R1 (K, V, PAD)
SELECT LEVEL, ROUND(0.5 + MOD(ORA_HASH(LEVEL, 4294967295, 10), 1000000) / 1000000, 6), RPAD('x', 100, 'x')
  FROM dual CONNECT BY LEVEL <= 200000
/
COMMIT
